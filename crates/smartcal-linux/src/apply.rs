pub const UDEV_PERMISSIONS_RULE: &str = r#"# SmartCal Classroom Smart Board & Interactive Projector Permissions
# Allows users in the 'input' group to read touchscreens and emit calibrated events without running GUI as root.
SUBSYSTEM=="input", KERNEL=="event*", ENV{ID_INPUT_TOUCHSCREEN}=="1", MODE="0660", GROUP="input"
SUBSYSTEM=="input", KERNEL=="event*", ENV{ID_INPUT_TABLET}=="1", MODE="0660", GROUP="input"
KERNEL=="uinput", MODE="0660", GROUP="input", OPTIONS+="static_node=uinput"
"#;

pub fn generate_udev_calibration_rule(profile: &CalibrationProfile) -> String {
    let m = profile.model.libinput_affine;
    format!(
        "# Generated by SmartCal for {dev} on {disp}\n\
         ACTION==\"add|change\", SUBSYSTEM==\"input\", \
         ENV{{ID_VENDOR_ID}}==\"{vid}\", ENV{{ID_MODEL_ID}}==\"{pid}\", \
         ENV{{LIBINPUT_CALIBRATION_MATRIX}}==\"{:.6} {:.6} {:.6} {:.6} {:.6} {:.6}\", \
         ENV{{WL_OUTPUT}}==\"{disp}\"\n",
        m[0],
        m[1],
        m[2],
        m[3],
        m[4],
        m[5],
        dev = profile.device_name,
        disp = profile.display,
        vid = profile.vendor_id,
        pid = profile.product_id,
    )
}

pub fn apply_calibration(profile: &CalibrationProfile) -> Result<ApplyResult> {
    let session = detect_session();
    record_log(
        LogLevel::Info,
        "apply",
        format!(
            "Applying calibration profile '{}' for '{}' on {} ({})",
            profile.profile_name, profile.device_name, profile.display, session.display_server
        ),
    );

    #[cfg(not(target_os = "linux"))]
    {
        Ok(ApplyResult {
            backend_used: "Preview Simulation (non-Linux host)".into(),
            applied_matrix: profile.model.x11_ctm,
            persisted_autostart: profile.auto_apply,
            requires_relogin_or_udev: false,
            warnings: vec![
                "Running on non-Linux host; calibration profile saved for deployment on Linux."
                    .into(),
            ],
        })
    }

    #[cfg(target_os = "linux")]
    {
        match session.display_server {
            DisplayServer::X11 => apply_x11(profile),
            DisplayServer::Wayland => apply_wayland(profile, session.compositor),
            DisplayServer::Unknown => apply_udev_only(profile),
        }
    }
}

pub fn reset_calibration(device: Option<&InputDeviceInfo>) -> Result<()> {
    let session = detect_session();
    record_log(
        LogLevel::Info,
        "reset",
        format!(
            "Resetting calibration (server: {}, device: {:?})",
            session.display_server,
            device.map(|d| &d.name)
        ),
    );

    #[cfg(target_os = "linux")]
    {
        let id_mat = identity_mat3();
        if session.display_server == DisplayServer::X11 {
            if let Some(dev) = device {
                if let Some(xi_id) = dev.xinput_id {
                    set_x11_ctm(xi_id, &dev.name, &id_mat)?;
                } else {
                    // Attempt lookup by name
                    let _ = set_x11_ctm_by_name(&dev.name, &id_mat);
                }
            } else {
                // Reset all touchscreens/tablets detected on X11
                for d in crate::inputs::detect_input_devices() {
                    if d.is_interactive_touch()
                        && let Some(xi_id) = d.xinput_id
                    {
                        let _ = set_x11_ctm(xi_id, &d.name, &id_mat);
                    }
                }
            }
        } else if session.display_server == DisplayServer::Wayland {
            if session.compositor == WaylandCompositor::Sway
                && let Some(dev) = device
            {
                let _ = std::process::Command::new("swaymsg")
                    .args([
                        "input",
                        &dev.name,
                        "calibration_matrix",
                        "1",
                        "0",
                        "0",
                        "0",
                        "1",
                        "0",
                    ])
                    .status();
            }
            let rule_path = std::path::Path::new("/etc/udev/rules.d/99-smartcal-calibration.rules");
            if rule_path.exists() {
                if std::fs::remove_file(rule_path).is_err() {
                    return Err(SmartCalError::InsufficientPermissions(
                        "Cannot remove /etc/udev/rules.d/99-smartcal-calibration.rules without elevated privileges".into(),
                    ));
                }
                reload_udev_rules();
            }
        }
    }

    let _ = (device, identity_mat3());
    Ok(())
}

#[cfg(target_os = "linux")]
fn apply_x11(profile: &CalibrationProfile) -> Result<ApplyResult> {
    let devices = crate::inputs::detect_input_devices();
    let matched = devices.iter().find(|d| {
        (!profile.vendor_id.is_empty()
            && d.vendor_id.eq_ignore_ascii_case(&profile.vendor_id)
            && d.product_id.eq_ignore_ascii_case(&profile.product_id))
            || d.name.eq_ignore_ascii_case(&profile.device_name)
    });

    let ctm = profile.model.x11_ctm;
    let mut warnings = Vec::new();
    if matches!(
        profile.method,
        CalibrationMethod::PolynomialDeg2
            | CalibrationMethod::PolynomialDeg3
            | CalibrationMethod::HybridTps
    ) {
        warnings.push(
            "X11 Coordinate Transformation Matrix applies projective linear transform; for full non-linear correction use `smartcal --daemon`.".into(),
        );
    }

    if let Some(dev) = matched {
        if let Some(xi_id) = dev.xinput_id {
            set_x11_ctm(xi_id, &dev.name, &ctm)?;
            return Ok(ApplyResult {
                backend_used: format!("X11 XInput2 (device id {xi_id})"),
                applied_matrix: ctm,
                persisted_autostart: profile.auto_apply,
                requires_relogin_or_udev: false,
                warnings,
            });
        }
        set_x11_ctm_by_name(&dev.name, &ctm)?;
        return Ok(ApplyResult {
            backend_used: "X11 xinput CLI".into(),
            applied_matrix: ctm,
            persisted_autostart: profile.auto_apply,
            requires_relogin_or_udev: false,
            warnings,
        });
    }

    // Try direct device name fallback
    set_x11_ctm_by_name(&profile.device_name, &ctm)?;
    Ok(ApplyResult {
        backend_used: "X11 xinput fallback".into(),
        applied_matrix: ctm,
        persisted_autostart: profile.auto_apply,
        requires_relogin_or_udev: false,
        warnings,
    })
}

#[cfg(target_os = "linux")]
fn set_x11_ctm(device_id: u32, device_name: &str, matrix: &[f64; 9]) -> Result<()> {
    use x11rb::connection::Connection;
    use x11rb::protocol::xinput::{self, ConnectionExt as XiExt};
    use x11rb::protocol::xproto::{self, ConnectionExt as XprotoExt};

    if let Ok((conn, _)) = x11rb::connect(None)
        && let Ok(atom_c) = conn.intern_atom(false, b"Coordinate Transformation Matrix")
        && let Ok(atom_r) = atom_c.reply()
        && let Ok(float_c) = conn.intern_atom(false, b"FLOAT")
        && let Ok(float_r) = float_c.reply()
    {
        let f32_bits: Vec<u32> = matrix.iter().map(|v| (*v as f32).to_bits()).collect();
        let items = xinput::XIChangePropertyAux::Data32(f32_bits);
        if conn
            .xinput_xi_change_property(
                device_id as u16,
                xproto::PropMode::REPLACE,
                atom_r.atom,
                float_r.atom,
                9,
                &items,
            )
            .is_ok()
            && conn.flush().is_ok()
        {
            return Ok(());
        }
    }

    // Fallback to xinput CLI if XInput2 call wasn't accepted
    set_x11_ctm_by_name(device_name, matrix)
}

#[cfg(target_os = "linux")]
fn set_x11_ctm_by_name(device_name: &str, matrix: &[f64; 9]) -> Result<()> {
    use std::process::Command;
    let args: Vec<String> = matrix.iter().map(|v| format!("{v:.6}")).collect();
    let out = Command::new("xinput")
        .arg("set-prop")
        .arg(device_name)
        .arg("Coordinate Transformation Matrix")
        .args(&args)
        .output();

    match out {
        Ok(o) if o.status.success() => Ok(()),
        Ok(o) => {
            let err = String::from_utf8_lossy(&o.stderr);
            if err.to_lowercase().contains("permission") {
                Err(SmartCalError::InsufficientPermissions(err.into_owned()))
            } else {
                Err(SmartCalError::Backend {
                    backend: "xinput".into(),
                    message: format!("Failed to set XInput matrix for '{device_name}': {err}"),
                })
            }
        }
        Err(e) => Err(SmartCalError::Backend {
            backend: "xinput".into(),
            message: format!("Could not execute xinput: {e}"),
        }),
    }
}

#[cfg(target_os = "linux")]
fn apply_wayland(
    profile: &CalibrationProfile,
    compositor: WaylandCompositor,
) -> Result<ApplyResult> {
    use std::process::Command;

    let mut warnings = vec![
        "Wayland compositors restrict direct global pointer injection; using compositor/libinput/udev calibration pipeline.".into(),
    ];
    let aff = profile.model.libinput_affine;

    // 1. Sway native runtime IPC
    if compositor == WaylandCompositor::Sway {
        let matrix_args = [
            "input",
            &profile.device_name,
            "calibration_matrix",
            &format!("{:.6}", aff[0]),
            &format!("{:.6}", aff[1]),
            &format!("{:.6}", aff[2]),
            &format!("{:.6}", aff[3]),
            &format!("{:.6}", aff[4]),
            &format!("{:.6}", aff[5]),
        ];
        let s1 = Command::new("swaymsg").args(matrix_args).status();
        let s2 = Command::new("swaymsg")
            .args([
                "input",
                &profile.device_name,
                "map_to_output",
                &profile.display,
            ])
            .status();
        if s1.is_ok_and(|s| s.success()) && s2.is_ok_and(|s| s.success()) {
            return Ok(ApplyResult {
                backend_used: "Wayland Sway IPC (swaymsg)".into(),
                applied_matrix: profile.matrix,
                persisted_autostart: profile.auto_apply,
                requires_relogin_or_udev: false,
                warnings,
            });
        }
    }

    // 2. GNOME / Mutter output mapping via gsettings (user-level, no root needed)
    if compositor == WaylandCompositor::Mutter
        && !profile.vendor_id.is_empty()
        && !profile.product_id.is_empty()
    {
        let schema_path = format!(
            "org.gnome.desktop.peripherals.touchscreen:/org/gnome/desktop/peripherals/touchscreens/{}:{}/",
            profile.vendor_id, profile.product_id
        );
        let _ = Command::new("gsettings")
            .args([
                "set",
                &schema_path,
                "output",
                &format!("['{}', '', '']", profile.display),
            ])
            .status();
    }

    // 3. Standard Wayland udev LIBINPUT_CALIBRATION_MATRIX rule
    match write_udev_calibration_rule(profile) {
        Ok(()) => Ok(ApplyResult {
            backend_used: format!("Wayland udev LIBINPUT_CALIBRATION_MATRIX ({compositor})"),
            applied_matrix: profile.matrix,
            persisted_autostart: profile.auto_apply,
            requires_relogin_or_udev: true,
            warnings,
        }),
        Err(e) => {
            warnings.push(
                "Note: Affine udev rule requires root/udev write access. You can install the rule via `sudo smartcal --install-udev-rule` or use `smartcal --daemon` if in the `input` group.".into(),
            );
            Err(e)
        }
    }
}

#[cfg(target_os = "linux")]
fn apply_udev_only(profile: &CalibrationProfile) -> Result<ApplyResult> {
    write_udev_calibration_rule(profile)?;
    Ok(ApplyResult {
        backend_used: "udev LIBINPUT_CALIBRATION_MATRIX".into(),
        applied_matrix: profile.matrix,
        persisted_autostart: profile.auto_apply,
        requires_relogin_or_udev: true,
        warnings: vec![],
    })
}

#[cfg(target_os = "linux")]
fn write_udev_calibration_rule(profile: &CalibrationProfile) -> Result<()> {
    let rule = generate_udev_calibration_rule(profile);
    let path = "/etc/udev/rules.d/99-smartcal-calibration.rules";
    match std::fs::write(path, rule) {
        Ok(()) => {
            reload_udev_rules();
            Ok(())
        }
        Err(e) if e.kind() == std::io::ErrorKind::PermissionDenied => Err(
            SmartCalError::InsufficientPermissions(format!("Write permission denied for {path}")),
        ),
        Err(e) => Err(SmartCalError::Io(e)),
    }
}

#[cfg(target_os = "linux")]
fn reload_udev_rules() {
    use std::process::Command;
    let _ = Command::new("udevadm")
        .args(["control", "--reload-rules"])
        .status();
    let _ = Command::new("udevadm")
        .args(["trigger", "--subsystem-match=input"])
        .status();
}

/// Installs the non-root classroom permissions udev rule (`/etc/udev/rules.d/99-smartcal-permissions.rules`).
pub fn install_permissions_udev_rule() -> Result<()> {
    #[cfg(target_os = "linux")]
    {
        let path = "/etc/udev/rules.d/99-smartcal-permissions.rules";
        match std::fs::write(path, UDEV_PERMISSIONS_RULE) {
            Ok(()) => {
                reload_udev_rules();
                record_log(
                    LogLevel::Info,
                    "udev",
                    "Installed 99-smartcal-permissions.rules and reloaded udev",
                );
                Ok(())
            }
            Err(e) if e.kind() == std::io::ErrorKind::PermissionDenied => {
                Err(SmartCalError::InsufficientPermissions(format!(
                    "Run with sudo/pkexec to write {path}"
                )))
            }
            Err(e) => Err(SmartCalError::Io(e)),
        }
    }
    #[cfg(not(target_os = "linux"))]
    {
        Err(SmartCalError::Unsupported(
            "udev rules are only applicable on Linux".into(),
        ))
    }
}

/// Runs a userspace `/dev/uinput` calibration remapping daemon for full Homography / Polynomial / TPS accuracy.
pub fn run_uinput_daemon(
    profile: &CalibrationProfile,
    stop: &std::sync::atomic::AtomicBool,
) -> Result<()> {
    #[cfg(not(target_os = "linux"))]
    {
        let _ = (profile, stop);
        Err(SmartCalError::Unsupported(
            "uinput calibration daemon requires Linux".into(),
        ))
    }

    #[cfg(target_os = "linux")]
    {
        use evdev::{
            AbsInfo, AbsoluteAxisCode, AttributeSet, Device, EventSummary, EventType, InputEvent,
            KeyCode, UinputAbsSetup, uinput::VirtualDevice,
        };
        use std::os::unix::io::AsRawFd;
        use std::sync::atomic::Ordering;

        let mut src_dev = Device::open(&profile.device_path).map_err(|e| {
            if e.kind() == std::io::ErrorKind::PermissionDenied {
                SmartCalError::InsufficientPermissions(format!(
                    "Cannot open {} for calibration daemon: {e}",
                    profile.device_path
                ))
            } else {
                SmartCalError::Io(e)
            }
        })?;

        let displays = detect_displays(detect_session().display_server);
        let disp: DisplayInfo = displays
            .iter()
            .find(|d| d.name == profile.display || d.id == profile.display_id)
            .cloned()
            .unwrap_or(DisplayInfo {
                id: profile.display_id.clone(),
                name: profile.display.clone(),
                friendly_label: profile.display.clone(),
                width: profile.resolution[0],
                height: profile.resolution[1],
                x: profile.display_position[0],
                y: profile.display_position[1],
                refresh_hz: 60.0,
                scale_factor: 1.0,
                primary: true,
                connected: true,
                physical_width_mm: None,
                physical_height_mm: None,
            });

        let virt_w = profile.virtual_desktop_size[0].max(disp.width) as i32;
        let virt_h = profile.virtual_desktop_size[1].max(disp.height) as i32;

        let mut keys = AttributeSet::<KeyCode>::new();
        keys.insert(KeyCode::BTN_TOUCH);
        keys.insert(KeyCode::BTN_LEFT);

        let abs_x =
            UinputAbsSetup::new(AbsoluteAxisCode::ABS_X, AbsInfo::new(0, 0, virt_w, 0, 0, 1));
        let abs_y =
            UinputAbsSetup::new(AbsoluteAxisCode::ABS_Y, AbsInfo::new(0, 0, virt_h, 0, 0, 1));

        let mut vdev = VirtualDevice::builder()
            .map_err(|e| {
                SmartCalError::InsufficientPermissions(format!("uinput unavailable: {e}"))
            })?
            .name("SmartCal Calibrated Touchscreen")
            .with_keys(&keys)
            .map_err(|e| SmartCalError::Backend {
                backend: "uinput".into(),
                message: e.to_string(),
            })?
            .with_absolute_axis(&abs_x)
            .map_err(|e| SmartCalError::Backend {
                backend: "uinput".into(),
                message: e.to_string(),
            })?
            .with_absolute_axis(&abs_y)
            .map_err(|e| SmartCalError::Backend {
                backend: "uinput".into(),
                message: e.to_string(),
            })?
            .build()
            .map_err(|e| {
                if e.kind() == std::io::ErrorKind::PermissionDenied {
                    SmartCalError::InsufficientPermissions(format!(
                        "Cannot create /dev/uinput: {e}"
                    ))
                } else {
                    SmartCalError::Io(e)
                }
            })?;

        src_dev.grab().map_err(|e| {
            SmartCalError::InsufficientPermissions(format!(
                "Could not grab {} exclusively: {e}",
                profile.device_path
            ))
        })?;

        record_log(
            LogLevel::Info,
            "daemon",
            format!(
                "Started uinput calibration daemon for '{}'",
                profile.device_name
            ),
        );

        let fd = src_dev.as_raw_fd();
        let mut tracker = smartcal_math::SingleTouchTracker::default();
        let mut touch_down_changed = None;

        while !stop.load(Ordering::SeqCst) {
            let mut pfd = libc::pollfd {
                fd,
                events: libc::POLLIN,
                revents: 0,
            };
            let res = unsafe { libc::poll(&mut pfd, 1, 100) };
            if res <= 0 {
                continue;
            }
            let Ok(events) = src_dev.fetch_events() else {
                break;
            };
            for ev in events {
                match ev.destructure() {
                    EventSummary::AbsoluteAxis(_, code, val) => match code {
                        AbsoluteAxisCode::ABS_MT_SLOT => tracker.set_current_slot(val),
                        AbsoluteAxisCode::ABS_MT_TRACKING_ID => tracker.on_tracking_id(val),
                        AbsoluteAxisCode::ABS_MT_POSITION_X => tracker.update_mt_x(val as f64),
                        AbsoluteAxisCode::ABS_MT_POSITION_Y => tracker.update_mt_y(val as f64),
                        AbsoluteAxisCode::ABS_X => tracker.update_abs_x(val as f64),
                        AbsoluteAxisCode::ABS_Y => tracker.update_abs_y(val as f64),
                        _ => {}
                    },
                    EventSummary::Key(_, k, val) => {
                        if k == KeyCode::BTN_TOUCH || k == KeyCode::BTN_LEFT {
                            tracker.on_btn_touch(val != 0);
                            touch_down_changed = Some(val);
                        }
                    }
                    EventSummary::Synchronization(_, _, _) => {
                        let mut out_events = Vec::new();
                        if let Some(raw_pt) = tracker.current_point()
                            && let Some(local_px) = evaluate_model_raw_to_screen(
                                &profile.model,
                                &profile.raw_bounds,
                                raw_pt,
                                profile.method,
                            )
                        {
                            let gx = (local_px.x + disp.x as f64)
                                .round()
                                .clamp(0.0, virt_w as f64)
                                as i32;
                            let gy = (local_px.y + disp.y as f64)
                                .round()
                                .clamp(0.0, virt_h as f64)
                                as i32;
                            out_events.push(InputEvent::new(
                                EventType::ABSOLUTE.0,
                                AbsoluteAxisCode::ABS_X.0,
                                gx,
                            ));
                            out_events.push(InputEvent::new(
                                EventType::ABSOLUTE.0,
                                AbsoluteAxisCode::ABS_Y.0,
                                gy,
                            ));
                        }
                        if let Some(down) = touch_down_changed.take() {
                            out_events.push(InputEvent::new(
                                EventType::KEY.0,
                                KeyCode::BTN_TOUCH.0,
                                down,
                            ));
                        }
                        if !out_events.is_empty() {
                            out_events.push(InputEvent::new(EventType::SYNCHRONIZATION.0, 0, 0));
                            let _ = vdev.emit(&out_events);
                        }
                    }
                    _ => {}
                }
            }
        }

        let _ = src_dev.ungrab();
        Ok(())
    }
}
